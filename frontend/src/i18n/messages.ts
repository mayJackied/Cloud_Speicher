export function lookupMessage(locale: Locale, path: string): string {
  const parts = path.split('.')
  let cur: string | Tree | undefined = messages[locale]
  for (const part of parts) {
    if (!cur || typeof cur === 'string' || !(part in cur)) {
      if (locale !== 'zh-CN') {
        return lookupMessage('zh-CN', path)
      }
      return path
    }
    cur = cur[part]
  }
  return typeof cur === 'string' ? cur : path
}
